// Cuts three hook versions per song out of the source MP3s (whole MPEG frames, no re-encoding)
// into ../clips/NN-V.mp3 (V = 1, 2, 3). Hook start times come from ../hooks.json
// ({ "23": [v1, v2, v3], ... } in seconds). Writes ../clips.js with, per song and version,
// [hook start, clip start, clip end] in seconds of the source track.
// Usage: node tools/cut-clips.js "D:\Tushars\Wedding\Gaana Tambola"
const fs = require('fs'), path = require('path');
const PAD_BEFORE = 5, PAD_AFTER = 3, HOOK = 25;
const root = path.join(__dirname, '..');
global.window = {}; require(path.join(root, 'data.js'));
const D = window.GT_DATA;
const HOOKS = JSON.parse(fs.readFileSync(path.join(root, 'hooks.json'), 'utf8'));

const BR1 = [0, 32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320];
const BR2 = [0, 8, 16, 24, 32, 40, 48, 56, 64, 80, 96, 112, 128, 144, 160];
const SR = [44100, 48000, 32000];
function frameAt(b, i) {
  if (i + 4 > b.length || b[i] !== 0xff || (b[i + 1] & 0xe0) !== 0xe0) return null;
  const ver = (b[i + 1] >> 3) & 3, layer = (b[i + 1] >> 1) & 3;
  const bri = b[i + 2] >> 4, sri = (b[i + 2] >> 2) & 3, pad = (b[i + 2] >> 1) & 1;
  if (ver === 1 || layer !== 1 || bri === 0 || bri === 15 || sri === 3) return null; // Layer III only
  const v1 = ver === 3, sr = SR[sri] / (v1 ? 1 : ver === 2 ? 2 : 4);
  return { len: Math.floor(((v1 ? 144 : 72) * (v1 ? BR1 : BR2)[bri] * 1000) / sr) + pad, sr, spf: v1 ? 1152 : 576 };
}
function slice(b, from, to) {
  let i = 0;
  if (b[0] === 0x49 && b[1] === 0x44 && b[2] === 0x33) i = 10 + ((b[6] & 127) << 21 | (b[7] & 127) << 14 | (b[8] & 127) << 7 | (b[9] & 127)) + ((b[5] & 0x10) ? 10 : 0);
  let t = 0, a = -1, aT = 0, z = -1, first = true;
  while (i < b.length) {
    const f = frameAt(b, i);
    if (!f || (first && !frameAt(b, i + f.len) && i + f.len < b.length)) { i++; continue; } // resync
    if (first) { // skip a Xing/Info/VBRI header frame: no audio, and it claims the whole track's length
      first = false;
      if (/Xing|Info|VBRI/.test(b.subarray(i + 4, i + 60).toString('latin1'))) { i += f.len; continue; }
    }
    if (a < 0 && t + f.spf / f.sr > from) { a = i; aT = t; }
    t += f.spf / f.sr; i += f.len;
    if (a >= 0 && t >= to) { z = i; break; }
  }
  if (a < 0) throw new Error('no frames');
  return { bytes: b.subarray(a, z < 0 ? i : z), start: aT, end: Math.min(t, to) };
}

const src = process.argv[2];
if (!src) { console.error('Pass the folder of source MP3s.'); process.exit(1); }
fs.mkdirSync(path.join(root, 'clips'), { recursive: true });
const r3 = (x) => Math.round(x * 1000) / 1000;
const meta = {}; let total = 0;
for (const [n, , , , , file] of D.songs) {
  const buf = fs.readFileSync(path.join(src, file));
  meta[n] = HOOKS[n].map((start, v) => {
    const r = slice(buf, Math.max(0, start - PAD_BEFORE), start + HOOK + PAD_AFTER);
    fs.writeFileSync(path.join(root, 'clips', `${String(n).padStart(2, '0')}-${v + 1}.mp3`), r.bytes);
    total += r.bytes.length;
    return [start, r3(r.start), r3(r.end)];
  });
}
fs.writeFileSync(path.join(root, 'clips.js'),
  '/* Generated by tools/cut-clips.js: song -> 3 versions of [hook start, clip start, clip end], seconds in the source track. */\n' +
  'window.GT_CLIPS = ' + JSON.stringify(meta) + ';\n');
console.log('cut', Object.keys(meta).length * 3, 'clips,', (total / 1e6).toFixed(1), 'MB');
